// Assemble a reviewable SQL candidate only. This script never connects to a DB.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const release = new URL('backend/release/', root);
const read = async path => (await readFile(new URL(path, root), 'utf8')).replace(/\r\n/g, '\n');
const hash = text => createHash('sha256').update(text).digest('hex');
export const contractFiles = [
  '20261013172822_public_workshop_browsing.sql',
  '20261020123021_archive_linkedin_workshop.sql',
  '20261021181340_workshop_lifecycle_contract.sql',
  '20261022170525_registration_service.sql',
  '20261022172429_meeting_link_access.sql',
  '20261023070718_profile_editor_contract.sql',
  '20261023081331_admin_workshop_contract.sql',
];

export async function assembleRelease() {
  const snapshotText = await read('backend/release/observed-schema.json');
  const { schema, project_ref, inspected_on } = JSON.parse(snapshotText);
  const expected = { ...schema };
  delete expected.schema_grants;
  expected.constraints = schema.constraints.filter(constraint => constraint.type !== 'n');
  expected.functions = schema.functions.map(({ acl: _acl, ...fn }) => fn);
  expected.function_permissions = schema.functions.flatMap(fn =>
    ['anon', 'authenticated', 'service_role'].map(role => ({
      schema: fn.schema, name: fn.name, args: fn.args, role,
      execute: fn.acl.split(',').some(entry => {
        const [grantee, permissions] = entry.replace(/[{}]/g, '').split('=');
        return (grantee === '' || grantee === role) && permissions.split('/')[0].includes('X');
      }),
    })));
  const inspection = (await read('backend/release/inspect-schema.sql')).trim().replace(/;$/, '');
  const inputs = ['backend/release/observed-schema.json', 'backend/release/inspect-schema.sql',
    'backend/release/compatibility-before.sql', ...contractFiles.map(name => `backend/supabase/migrations/${name}`),
    'backend/release/compatibility-after.sql'];
  const contents = await Promise.all(inputs.map(read));
  const baseline = JSON.stringify(expected, null, 2);
  if (baseline.includes('$workify_baseline$')) throw new Error('Unexpected baseline delimiter.');
  const guard = `do $workify_guard$
declare actual jsonb; expected jsonb := $workify_baseline$${baseline}$workify_baseline$::jsonb; section text;
begin
  select snapshot into actual from (${inspection}) inspected;
  for section in select jsonb_object_keys(expected) loop
    if actual->section is distinct from expected->section then
      raise exception 'Release baseline drift in %. Reinspect and review; nothing applied.', section;
    end if;
  end loop;
end $workify_guard$;`;
  const sections = inputs.slice(2).map((path, index) => {
    // Adapt exactly the existing helper reference; no public definer wrapper.
    const sql = contents[index + 2].replaceAll('public.is_admin()', 'private.is_admin()');
    return `-- SOURCE: ${path}\n${sql.trim()}\n`;
  });
  const sql = `-- GENERATED by node scripts/build-release.mjs; review before applying.
-- Target baseline: ${project_ref}, inspected ${inspected_on}. No seed replay.
-- Run as one transaction on an authorized staging clone first.
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
set local search_path = public, pg_catalog;
lock table public.admin_users, public.linkedin_reviews, public.profiles,
  public.registrations, public.workshop_links, public.workshops in share row exclusive mode;
${guard}
${sections.join('\n')}
commit;
`;
  return { sql, manifest: { project_ref, inspected_on, sql_sha256: hash(sql),
    inputs: inputs.map((path, index) => ({ path, sha256: hash(contents[index]) })) } };
}

export async function releaseFile() {
  const directory = new URL('supabase/migrations/', release);
  const files = (await readdir(directory)).filter(name => /^\d{14}_reconcile_workify_existing_backend\.sql$/.test(name));
  if (files.length !== 1) throw new Error('Expected one CLI-generated reconciliation migration.');
  return new URL(files[0], directory);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { sql, manifest } = await assembleRelease();
  const output = await releaseFile();
  if (process.argv.includes('--check')) {
    if ((await readFile(output, 'utf8')).replace(/\r\n/g, '\n') !== sql) throw new Error('Release SQL is stale; regenerate and review it.');
    const saved = JSON.parse(await readFile(new URL('manifest.json', release), 'utf8'));
    if (JSON.stringify(saved) !== JSON.stringify(manifest)) throw new Error('Release manifest is stale.');
    console.log('Release SQL and all source hashes match.');
  } else {
    await writeFile(output, sql);
    await writeFile(new URL('manifest.json', release), `${JSON.stringify(manifest, null, 2)}\n`);
    console.log(`Prepared ${fileURLToPath(output)}\nSHA-256 ${manifest.sql_sha256}\nNo database connection or deployment performed.`);
  }
}
